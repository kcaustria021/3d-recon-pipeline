def compute_iou(gt_mask, recon_mask):
    """
    Computes the intersection over union (IoU) 
    between the true mask and the mask generated by the reconstruction
    """
    intersection = np.sum(np.logical_and(gt_mask, recon_mask))
    union = np.sum(np.logical_or(gt_mask, recon_mask))
    return intersection / union if union > 0 else 0.0

