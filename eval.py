def get_gt_pts(input_path, n_pts=10000):
    """
    Get the point cloud of the ground truth
    """
    mesh = trimesh.load(input_path)
    pts = mesh.sample(n_pts)
    return pts

def get_pred_pts(input_path):
    """
    Get the point cloud of the reconstruction
    """
    if input_path.endswith(".ply"):
        pcd = o3d.io.read_point_cloud(input_path)
        return np.asarray(pcd.points)
    elif input_path.endswith(".npy"):
        return np.load(input_path)
    else:
        raise ValueError("Point cloud file must be .ply or .npy")
    
def get_mesh(pts, output_file):
    pcd = o3d.geometry.PointCloud()
    pcd.points = o3d.utility.Vector3dVector(pts)
    pcd.estimate_normals(
        search_param=o3d.geometry.KDTreeSearchParamKNN(knn=50)
    )
    pcd.orient_normals_consistent_tangent_plane(100)
    mesh, densities = o3d.geometry.TriangleMesh.create_from_point_cloud_poisson(
        pcd,
        depth=9
    )

    densities = np.asarray(densities)
    threshold = np.quantile(densities, 0.05)

    to_keep = densities > threshold
    mesh.remove_vertices_by_mask(~to_keep)

    # visualize
    o3d.visualization.draw_geometries([mesh])

    # save mesh
    try:
        o3d.io.write_triangle_mesh(output_file, mesh)
        print("Mesh saved successfully")
    except Exception as e:
        print(e)
    return mesh

